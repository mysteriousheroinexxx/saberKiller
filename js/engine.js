function shoot(){
  if(P.dead||WS.paused||!WS.playing)return;
  const w=WEAPONS[P.weapon];
  if(P.cool>0||P.reloadT>0)return;
  if(P.mag[w.ammo]<=0){
    if(P[w.ammo]>0){startReload();}
    else {SND.empty();P.cool=.25;}
    return;
  }
  P.mag[w.ammo]--;P.cool=w.rate;P.kick=w.kick;
  if(P.mag[w.ammo]===0&&P[w.ammo]>0)startReload();
  P.pitch+=w.kick*.35;
  if(P.weapon===0)SND.pistol();else SND.shotgun();
  muzzleSprite.visible=true;muzzleSprite.material.rotation=R(0,6.28);
  muzzleLight.intensity=3.2;
  setTimeout(()=>{muzzleSprite.visible=false;},45);

  camera.getWorldDirection(_dir);
  let wallTargets=[];
  if(customCollision&&typeof customCollision.getRaycastTargets==='function'){
    wallTargets=customCollision.getRaycastTargets();
  }else{
    wallTargets=wallMeshes.filter(m=>m.visible);
  }
  const targets=wallTargets.concat(hitMeshes);
  for(let i=0;i<w.pellets;i++){
    _dir.copy(camera.getWorldDirection(new THREE.Vector3()));
    _dir.x+=R(-w.spread,w.spread);_dir.y+=R(-w.spread,w.spread);_dir.z+=R(-w.spread,w.spread);
    _dir.normalize();
    raycaster.set(camera.getWorldPosition(new THREE.Vector3()),_dir);
    raycaster.far=80;
    const hits=raycaster.intersectObjects(targets,false);
    let end=raycaster.ray.at(60,new THREE.Vector3());
    if(hits.length){
      const h=hits[0];end=h.point;
      const zb=h.object.userData.zb;
      if(zb){
        // GLB model: hair is part of the body mesh and covers the head,
        // so count any hit above shoulder height as a headshot
        const headshot = zb.rigid
          ? h.point.y > zb.group.position.y + 1.5*zb.scale
          : (h.object===zb.parts.head||h.object.parent===zb.parts.head);
        damageZombie(zb,w.dmg*(headshot?2:1),h.point,headshot);
      } else {
        sparkBurst(h.point,4);
      }
    }
    // tracer from muzzle world pos
    muzzleSprite.getWorldPosition(_from);
    addTracer(_from.clone(),end.clone());
  }
}
