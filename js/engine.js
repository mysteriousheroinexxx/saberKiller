function skinnedWorldBox(root){
  // true world bbox of skinned meshes (bone-deformed), not the bind-pose geometry box
  root.updateMatrixWorld(true);
  const box=new THREE.Box3();const v=new THREE.Vector3();const bm=new THREE.Matrix4();
  root.traverse(o=>{
    if(!o.isSkinnedMesh)return;
    o.skeleton.update();
    const pos=o.geometry.attributes.position.array;
    const si=o.geometry.attributes.skinIndex.array, sw=o.geometry.attributes.skinWeight.array;
    const bones=o.skeleton.boneMatrices;const n=o.geometry.attributes.position.count;
    for(let i=0;i<n;i++){
      v.set(pos[i*3],pos[i*3+1],pos[i*3+2]).applyMatrix4(o.bindMatrixInverse);
      let x=0,y=0,z=0;const tx=v.x,ty=v.y,tz=v.z;
      for(let j=0;j<4;j++){
        const w=sw[i*4+j];if(w===0)continue;
        bm.fromArray(bones,si[i*4+j]*16);const e=bm.elements;
        x+=(e[0]*tx+e[4]*ty+e[8]*tz+e[12])*w;
        y+=(e[1]*tx+e[5]*ty+e[9]*tz+e[13])*w;
        z+=(e[2]*tx+e[6]*ty+e[10]*tz+e[14])*w;
      }
      v.set(x,y,z).applyMatrix4(o.bindMatrix).applyMatrix4(o.matrixWorld);
      box.expandByPoint(v);
    }
  });
  return box;
}
