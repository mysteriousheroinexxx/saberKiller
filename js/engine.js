function computeReach(){
  _reach.clear();floorCells.length=0;
  const stack=[[16,16]];
  while(stack.length){
    const [x,z]=stack.pop();const k=x+','+z;
    if(_reach.has(k)||isWall(x,z))continue;
    _reach.add(k);
    stack.push([x+1,z],[x-1,z],[x,z+1],[x,z-1]);
  }
  for(let z=0;z<MAPH;z++)for(let x=0;x<MAPW;x++)
    if(grid[z][x]===0&&_reach.has(x+','+z))floorCells.push([x,z]);
}
