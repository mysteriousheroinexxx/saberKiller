    fx/=len;fz/=len;
    const sin=Math.sin(P.yaw),cos=Math.cos(P.yaw);
    const mx=(fx*cos+fz*sin)*speed*dt;
    const mz=(-fx*sin+fz*cos)*speed*dt;
    const r=.32;
    let nx=P.pos.x+mx;
    if(!circleHitsWall(nx,P.pos.z,r))P.pos.x=nx;
