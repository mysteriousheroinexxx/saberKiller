  P.grinT=Math.max(0,P.grinT-dt);P.winceT=Math.max(0,P.winceT-dt);
  if(hitMarkT>0){hitMarkT-=dt;if(hitMarkT<=0){$('crosshair').classList.remove('hit');$('hitmarker').classList.remove('show');}}
  if(msgT>0){msgT-=dt;if(msgT<=0)$('pickupMsg').style.opacity=0;}

  const sprint=keys['ShiftLeft']||keys['ShiftRight'];
  const speed=sprint?7.6:5.2;
  let fx=0,fz=0;
  if(keys['KeyW']||keys['ArrowUp'])fz-=1;
  if(keys['KeyS']||keys['ArrowDown'])fz+=1;
