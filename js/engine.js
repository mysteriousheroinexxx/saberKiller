let mouseDown=false;
let cursorMode=false;
function bindInput(){
  addEventListener('keydown',e=>{
    if(e.code==='AltLeft'){
      e.preventDefault();
      if(locked){cursorMode=true;document.exitPointerLock?.();}
      else if(WS.playing&&!WS.paused&&!Dialogue.isActive()){
        cursorMode=false;tryLock();
      }
      return;
    }
    if(Dialogue.isActive()){
      if(e.code==='ArrowUp'||e.code==='ArrowDown'){
        Dialogue.moveChoice(e.code==='ArrowDown'?1:-1);e.preventDefault();return;
      }
      if(e.code==='Space'||e.code==='Enter'){Dialogue.choose();e.preventDefault();}
      return;
    }
    if(e.code==='KeyE'&&WS.playing&&!WS.paused){
      if(runLevelHook('interact')!==true&&nearNPC){runLevelHook('npcInteract',nearNPC);Dialogue.open(nearNPC.tree,'start');}
      e.preventDefault();return;
    }
    if(e.code==='KeyI'&&WS.playing&&!Dialogue.isActive()){toggleInventory();e.preventDefault();return;}
    if(e.code==='KeyR'&&WS.playing&&!WS.paused&&!Dialogue.isActive()){startReload();e.preventDefault();return;}
    keys[e.code]=true;
    if(e.code==='Digit1'&&P.weapon!==0){P.weapon=0;P.switchT=.22;gunPistol.visible=true;gunShotgun.visible=false;}
    if(e.code==='Digit2'&&P.weapon!==1){P.weapon=1;P.switchT=.22;gunPistol.visible=false;gunShotgun.visible=true;}
    if(['Space','ArrowUp','ArrowDown'].includes(e.code))e.preventDefault();
  });
  addEventListener('keyup',e=>{keys[e.code]=false;if(e.code==='AltLeft')e.preventDefault();});
  addEventListener('mousedown',e=>{
    if(e.button===0){mouseDown=true;if(WS.playing&&!WS.paused)shoot();}
  });
  addEventListener('mouseup',e=>{if(e.button===0)mouseDown=false;});
  addEventListener('mousemove',e=>{
    if(!WS.playing||WS.paused)return;
    let dx=0,dy=0;
    if(locked){dx=e.movementX;dy=e.movementY;}
    else if(dragLook&&mouseDown){dx=e.clientX-lastMX;dy=e.clientY-lastMY;}
    lastMX=e.clientX;lastMY=e.clientY;
    P.yaw-=dx*.0023*SETTINGS.get().sens;
    P.pitch-=dy*.0023*SETTINGS.get().sens;
    P.pitch=Math.max(-1.45,Math.min(1.45,P.pitch));
  });
  document.addEventListener('pointerlockchange',()=>{
    locked=document.pointerLockElement===renderer.domElement;
    if(!locked&&WS.playing&&!P.dead&&!cursorMode&&!Dialogue.isActive()){
      WS.paused=true;$('pauseScreen').classList.remove('hidden');
    }
  });
  document.addEventListener('pointerlockerror',()=>{dragLook=true;});
  addEventListener('resize',()=>{
    camera.aspect=innerWidth/innerHeight;camera.updateProjectionMatrix();
    renderer.setSize(innerWidth,innerHeight);
    if(postRenderTarget){
      postRenderTarget.setSize(innerWidth,innerHeight);
      if(postMat)postMat.uniforms.uResolution.value.set(innerWidth,innerHeight);
    }
  });
  $('startBtn').onclick=()=>startGame(true);
  $('resumeBtn').onclick=()=>{
    $('pauseScreen').classList.add('hidden');WS.paused=false;tryLock();
  };
  $('restartBtn').onclick=()=>{resetGame();startGame(true);};
  // settings panel (persisted)
  const refreshSettingsLabels=()=>{const s=SETTINGS.get();
    $('sensVal').textContent=s.sens.toFixed(1);
    $('volVal').textContent=Math.round(s.volume*100)+'%';
    $('fovVal').textContent=s.fov;};
  let settingsReturn='startScreen';
  const openSettings=from=>{settingsReturn=from;$(from).classList.add('hidden');
    const s=SETTINGS.get();$('sensSlider').value=s.sens;$('volSlider').value=s.volume;$('fovSlider').value=s.fov;
    refreshSettingsLabels();$('settingsScreen').classList.remove('hidden');};
  $('settingsBtn').onclick=()=>openSettings('startScreen');
  $('settingsBtn2').onclick=()=>openSettings('pauseScreen');
  $('settingsBackBtn').onclick=()=>{$('settingsScreen').classList.add('hidden');$(settingsReturn).classList.remove('hidden');};
  $('invBackBtn').onclick=toggleInventory;
  $('useWaterBtn').onclick=useAlmondWater;
  $('sensSlider').oninput=e=>{SETTINGS.set('sens',parseFloat(e.target.value));refreshSettingsLabels();};
  $('volSlider').oninput=e=>{SETTINGS.set('volume',parseFloat(e.target.value));refreshSettingsLabels();};
  $('fovSlider').oninput=e=>{SETTINGS.set('fov',parseInt(e.target.value));refreshSettingsLabels();};
  SETTINGS.apply();
}
