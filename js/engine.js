function updateZombies(dt){
  const px=P.pos.x,pz=P.pos.z;
  mission.hitCooldown=Math.max(0,(mission.hitCooldown||0)-dt);
  for(const zb of [...zombies]){
    const g=zb.group;
    if(zb.mixamo)zb.mixer.update(dt);
    else if(zb.animated)animateZombie(zb);
    if(zb.flashT>0){zb.flashT-=dt;
      if(zb.flashT<=0)for(const m of zb.mats)if(m.emissive)m.emissive.setRGB(0,0,0);}
    if(zb.state==='rise'){
      zb.riseT+=dt;
      g.position.y=-1.7*(1-Math.min(1,zb.riseT/.7));
      if(zb.riseT>=.7){zb.state='chase';g.position.y=0;}
      continue;
    }
    if(zb.state==='dying'){
      zb.dieT+=dt;
      if(zb.mixamo){
        if(!zb.deathStarted){zb.deathStarted=true;zb.attacks.forEach(a=>a.stop());g.rotation.y+=ZMODEL.deathYaw||0;zb.death.reset().play();zb.walk.crossFadeTo(zb.death,0.12);}
        const dd=ZMODEL.deathDur;
        if(zb.dieT>dd+1.5)g.position.y=-(zb.dieT-dd-1.5)*1.2;
        if(zb.dieT>dd+3.0)removeZombie(zb);
      } else {
        g.rotation.x=Math.min(Math.PI/2,zb.dieT*2.6); // topple backward (rigid + skeletal)
        if(zb.dieT>1.4)g.position.y=-(zb.dieT-1.4)*1.2;
        if(zb.dieT>2.5)removeZombie(zb);
      }
      continue;
    }
    // chase
    const target=mission.active&&mission.target?mission.target:null;
    const tx=target?target.x:px,tz=target?target.z:pz;
    const dx=tx-g.position.x,dz=tz-g.position.z;
    const dist=Math.hypot(dx,dz)||.001;
    let vx=dx/dist*zb.speed,vz=dz/dist*zb.speed;
    if(target&&dist<1.55){vx=0;vz=0;}
    // separation
    for(const o of zombies){
      if(o===zb||o.state==='dying')continue;
      const sx=g.position.x-o.group.position.x,sz=g.position.z-o.group.position.z;
      const sd=Math.hypot(sx,sz);
      if(sd<.95&&sd>.001){vx+=sx/sd*1.4;vz+=sz/sd*1.4;}
    }
    vx+=zb.kbx;vz+=zb.kbz;
    if(target){
      const mx=vx*dt,mz=vz*dt,nx=g.position.x+mx,nz=g.position.z+mz;
      const nd=Math.hypot(target.x-nx,target.z-nz);
      if(nd<1.35){
        const safe=1.35,rx=target.x-g.position.x,rz=target.z-g.position.z,rd=Math.hypot(rx,rz);
        if(dist<safe){
          const ux=rd>.001?rx/rd:Math.cos(zb.phase),uz=rd>.001?rz/rd:Math.sin(zb.phase);
          vx=-ux*Math.min(zb.speed,(safe-dist)*5);vz=-uz*Math.min(zb.speed,(safe-dist)*5);
        }
        else {const allowed=Math.max(0,dist-safe)/Math.max(.001,dist-nd);vx*=allowed;vz*=allowed;}
      }
    }
    zb.kbx*=Math.pow(.02,dt);zb.kbz*=Math.pow(.02,dt);
    // move with wall sliding
    const r=.34*zb.scale;
    let nx=g.position.x+vx*dt;
    if(!circleHitsWall(nx,g.position.z,r))g.position.x=nx;
    let nz=g.position.z+vz*dt;
    if(!circleHitsWall(g.position.x,nz,r))g.position.z=nz;
    // stuck safety net: if blocked for 2.5s while far from the player,
    // re-emerge elsewhere so a wave can never stall on wedged geometry
    // (close range = attacking, not stuck)
    const moved=Math.hypot(g.position.x-zb.lastX,g.position.z-zb.lastZ);
    zb.stuckT = (dist>2 && moved < zb.speed*dt*.15) ? zb.stuckT+dt : 0;
    zb.lastX=g.position.x;zb.lastZ=g.position.z;
    if(zb.stuckT>2.5){
      zb.stuckT=0;
      for(let t=0;t<30;t++){
        const [cx,cz]=floorCells[(rng()*floorCells.length)|0];
        const [wx2,wz2]=cellCenter(cx,cz);
        const d=Math.hypot(wx2-tx,wz2-tz);
        if(d>6&&d<18&&!circleHitsWall(wx2,wz2,r)){
          g.position.set(wx2,0,wz2);zb.lastX=wx2;zb.lastZ=wz2;break;
        }
      }
    }
    // face player. GLB model front is +Z; game convention is -Z, so add 180°.
    g.rotation.y=Math.atan2(-dx,-dz)+((zb.animated||zb.mixamo)?Math.PI:0);
    zb.phase+=dt*zb.speed*3.4;
    if(zb.attackAnimT>0)zb.attackAnimT-=dt;
    if(zb.mixamo){
      g.position.y=0; // clip-driven locomotion, feet grounded
    } else if(zb.animated){
      g.position.y=Math.abs(Math.sin(zb.phase))*0.05; // walk bob
    } else if(zb.rigid){
      // rigid GLB zombie: shuffle bob, sway, head loll, sword swing
      g.rotation.x=.07;
      g.rotation.z=Math.sin(zb.phase)*.05;
      g.position.y=Math.abs(Math.sin(zb.phase))*.06;
      const t=performance.now()/1000;
      if(zb.parts.head){
        zb.parts.head.rotation.z=Math.sin(t*.7+zb.phase)*.16;
        zb.parts.head.rotation.x=.1+Math.sin(t*.4+zb.phase)*.08;
      }
      if(zb.parts.sword){
        zb.parts.sword.rotation.x = zb.attackAnimT>0
          ? .3+(1-zb.attackAnimT/.28)*2.0
          : .15+Math.sin(zb.phase*.5)*.06;
      }
    } else {
      // procedural box zombie
      const sw=Math.sin(zb.phase)*.55;
      zb.parts.legL.rotation.x=sw;zb.parts.legR.rotation.x=-sw;
      if(zb.attackAnimT>0){
        zb.parts.armL.rotation.x=2.2;zb.parts.armR.rotation.x=2.2;
      } else {
        zb.parts.armL.rotation.x=1.25+Math.sin(zb.phase*.7)*.18;
        zb.parts.armR.rotation.x=1.25+Math.cos(zb.phase*.7)*.18;
      }
      zb.parts.jaw.rotation.x=Math.abs(Math.sin(zb.phase*.5))*.3;
      g.position.y=Math.abs(Math.sin(zb.phase))*.045;
    }
    // attack
    zb.attackCool-=dt;
    const attackRange=target?1.7:1.35;
    if(dist<attackRange&&zb.attackCool<=0&&!P.dead){
      zb.attackCool=zb.mixamo?1.4:1.1;zb.attackAnimT=.28;
      if(zb.mixamo){const ac=zb.attacks[(rng()*zb.attacks.length)|0];ac.reset().play();zb.walk.crossFadeTo(ac,0.1);}
      if(target&&mission.onHit){
        if(mission.hitCooldown<=0){mission.hitCooldown=2.2;mission.onHit(3+((rng()*3)|0));}
      }
      else hurtPlayer(9+((rng()*7)|0));
    }
    // groan
    zb.groanT-=dt;
    if(zb.groanT<=0){
      zb.groanT=R(4,9);
      if(dist<20)SND.groan(Math.max(.15,1-dist/22));
    }
  }
}

