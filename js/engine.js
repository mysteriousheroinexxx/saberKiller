function fitWeapon(model,holder,targetLen,fixedRot){
  while(holder.children.length)holder.remove(holder.children[0]);
  model.updateMatrixWorld(true);
  // sample world vertices to find muzzle (farthest from centroid) + grip direction
  const pts=[];const v=new THREE.Vector3();
  model.traverse(o=>{if(o.isMesh){const p=o.geometry.attributes.position;
    for(let i=0;i<p.count;i+=2){v.fromBufferAttribute(p,i).applyMatrix4(o.matrixWorld);pts.push(v.clone());}}});
  const c=new THREE.Vector3();pts.forEach(p=>c.add(p));c.divideScalar(pts.length);
  let muzzle=pts[0],md=-1;pts.forEach(p=>{const d=p.distanceToSquared(c);if(d>md){md=d;muzzle=p;}});
  const barrel=muzzle.clone().sub(c).normalize();
  const grip=new THREE.Vector3();let gc=0;const thresh=0.18*Math.sqrt(md);
  pts.forEach(p=>{const rel=p.clone().sub(c);const perp=rel.sub(barrel.clone().multiplyScalar(rel.dot(barrel)));
    if(perp.length()>thresh){grip.add(perp);gc++;}});
  if(gc>0)grip.divideScalar(gc).normalize();else grip.set(0,-1,0);
  let q;
  if(fixedRot){q=new THREE.Quaternion().setFromEuler(new THREE.Euler(fixedRot[0],fixedRot[1],fixedRot[2]));}
  else{
    const q1=new THREE.Quaternion().setFromUnitVectors(barrel,new THREE.Vector3(0,0,-1));
    const ga=grip.clone().applyQuaternion(q1);ga.z=0;
    if(ga.lengthSq()<1e-6)ga.set(0,-1,0);ga.normalize();
    const q2=new THREE.Quaternion().setFromUnitVectors(ga,new THREE.Vector3(0,-1,0));
    q=q2.multiply(q1);
  }
  const box=new THREE.Box3();pts.forEach(p=>box.expandByPoint(p));
  const size=box.getSize(new THREE.Vector3());
  const s=targetLen/(Math.max(size.x,size.y,size.z)||1);
  model.position.sub(c);
  model.traverse(o=>{if(o.isMesh){const src=o.material||{};
    o.material=new THREE.MeshLambertMaterial({map:src.map||null,
      color:src.color?src.color.clone():new THREE.Color(0x999999),emissive:0x0a0a0a});o.frustumCulled=false;}});
  const wrap=new THREE.Group();wrap.add(model);
  wrap.quaternion.copy(q);wrap.scale.setScalar(s);wrap.position.set(0,.02,-.18);
  holder.add(wrap);holder.userData.weaponWrap=wrap;
}

